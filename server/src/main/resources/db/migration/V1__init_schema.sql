COMMENT ON COLUMN public.interview_sessions.id IS '面试会话记录主键';



COMMENT ON COLUMN public.interview_sessions.created_at IS '面试会话创建时间';



COMMENT ON COLUMN public.interview_sessions.current_question_index IS '当前进行到的题目索引';



COMMENT ON COLUMN public.interview_sessions.questions_json IS '面试题目列表JSON';



COMMENT ON COLUMN public.interview_sessions.session_id IS '面试会话业务唯一标识';



COMMENT ON COLUMN public.interview_sessions.status IS '当前面试会话状态';



COMMENT ON COLUMN public.interview_sessions.total_questions IS '本次面试生成的题目总数量';



COMMENT ON COLUMN public.interview_sessions.resume_id IS '关联简历';



CREATE SEQUENCE public.interview_sessions_id_seq
    START WITH 1
    INCREMENT BY 1
    NO MINVALUE
    NO MAXVALUE
    CACHE 1;




ALTER SEQUENCE public.interview_sessions_id_seq OWNED BY public.interview_sessions.id;



