






CREATE TABLE public.interview_answers (
    id bigint NOT NULL,
    answered_at timestamp(6) without time zone NOT NULL,
    category character varying(100),
    feedback text,
    key_points_json text,
    question text NOT NULL,
    question_index integer NOT NULL,
    reference_answer text,
    score integer,
    user_answer text,
    session_id bigint NOT NULL
);




ALTER TABLE public.interview_answers ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY (
    SEQUENCE NAME public.interview_answers_id_seq
    START WITH 1
    INCREMENT BY 1
    NO MINVALUE
    NO MAXVALUE
    CACHE 1
);



CREATE TABLE public.interview_sessions (
    id bigint NOT NULL,
    created_at timestamp(6) without time zone NOT NULL,
    current_question_index integer NOT NULL,
    questions_json text NOT NULL,
    session_id character varying(36) NOT NULL,
    status character varying(20) NOT NULL,
    total_questions integer NOT NULL,
    resume_id bigint NOT NULL,
    skill_id character varying(64) NOT NULL,
    CONSTRAINT interview_sessions_status_check CHECK (((status)::text = ANY ((ARRAY['CREATED'::character varying, 'IN_PROGRESS'::character varying, 'COMPLETED'::character varying])::text[])))
);




