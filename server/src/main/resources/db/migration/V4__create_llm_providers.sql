-- V4：LLM Provider 配置表
-- 为什么要有这张表：A 期的 Provider 配置写在 application.yml 里，改配置要重启、密钥明文、
-- 多实例容易配置漂移、无法在线管理。搬到数据库后可以加密存储、可以停用、可以运行时修改。
-- 表里只存密文：api_key_ciphertext + api_key_nonce 由应用层用 AES-GCM 加解密，
-- 加密密钥本身放在环境变量里，不进数据库、不进代码。
-- 不预置数据：密文无法用 SQL 生成，首次启动时由应用从 application.yml 导入现有配置。
-- 与 interview_sessions.llm_provider 的关系：那边存的是 Provider 名字快照，故意不加外键，
-- 这样停用或替换 Provider 配置时，历史会话依然能读出当时用的是哪个模型。
-- temperature 用字符串存储（如 '0.20'）：本表只有少量配置行，不做数值比较和聚合，
-- 用字符串可以让实体字段保持 String，读取时由应用转成 double，转换逻辑集中在一处。

CREATE TABLE public.llm_providers (
    id bigint GENERATED BY DEFAULT AS IDENTITY,
    provider_key varchar(64) NOT NULL,
    display_name varchar(100),
    base_url varchar(512) NOT NULL,
    api_key_ciphertext varchar(4096) NOT NULL,
    api_key_nonce varchar(64) NOT NULL,
    model varchar(128) NOT NULL,
    embedding_model varchar(128),
    embedding_dimensions integer,
    supports_embedding boolean DEFAULT false NOT NULL,
    temperature varchar(10) DEFAULT '0.20' NOT NULL,
    enabled boolean DEFAULT true NOT NULL,
    builtin boolean DEFAULT false NOT NULL,
    created_at timestamp(6) without time zone DEFAULT now() NOT NULL,
    updated_at timestamp(6) without time zone DEFAULT now() NOT NULL,
    CONSTRAINT llm_providers_pkey PRIMARY KEY (id),
    CONSTRAINT uk_llm_providers_provider_key UNIQUE (provider_key),
    CONSTRAINT llm_providers_temperature_check CHECK (
        temperature ~ '^[0-9]+(\.[0-9]{1,2})?$'
        AND temperature::numeric >= 0
        AND temperature::numeric <= 2
    ),
    CONSTRAINT llm_providers_embedding_dimensions_check CHECK (embedding_dimensions IS NULL OR embedding_dimensions > 0)
);

COMMENT ON TABLE public.llm_providers IS 'LLM Provider 配置表';

COMMENT ON COLUMN public.llm_providers.id IS '配置主键';

COMMENT ON COLUMN public.llm_providers.provider_key IS 'Provider 唯一标识，程序内引用名，如 qwen';

COMMENT ON COLUMN public.llm_providers.display_name IS '展示名称，为空时前端回退显示 provider_key';

COMMENT ON COLUMN public.llm_providers.base_url IS '服务地址，不含结尾的 /v1';

COMMENT ON COLUMN public.llm_providers.api_key_ciphertext IS 'API Key 密文，Base64 编码，禁止存明文';

COMMENT ON COLUMN public.llm_providers.api_key_nonce IS 'AES-GCM 每次加密使用的随机数，Base64 编码，与密文成对使用';

COMMENT ON COLUMN public.llm_providers.model IS '对话模型名称';

COMMENT ON COLUMN public.llm_providers.embedding_model IS '向量模型名称，知识库检索使用，可为空';

COMMENT ON COLUMN public.llm_providers.embedding_dimensions IS '向量维度，与向量模型匹配，可为空';

COMMENT ON COLUMN public.llm_providers.supports_embedding IS '是否支持向量化，false 时不能用于知识库';

COMMENT ON COLUMN public.llm_providers.temperature IS '采样温度，字符串存储如 0.20，取值 0 到 2';

COMMENT ON COLUMN public.llm_providers.enabled IS '是否启用，停用而不删除以保留历史会话的可读性';

COMMENT ON COLUMN public.llm_providers.builtin IS '是否为系统内置配置，内置配置不允许普通用户删除';

COMMENT ON COLUMN public.llm_providers.created_at IS '配置创建时间';

COMMENT ON COLUMN public.llm_providers.updated_at IS '配置最后更新时间';
